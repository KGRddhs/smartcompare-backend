def test_merge_does_not_carry_stale_render_only_status():
    # THE TRAP: the idempotent merge preserves a prior status so the liveness
    # gate's verdict is never clobbered. A prior "render-only" is a verdict
    # ABOUT a render-only row — carrying it onto a row that is no longer
    # render-only would silently undo every flip this unit makes.
    rows = [{"domain": "x.com", "is_render_only": False,
             "status": "provider-test-candidate"}]
    build._merge_prior_verdicts(rows, {"x.com": {"status": "render-only"}})
    assert rows[0]["status"] == "provider-test-candidate"


def test_merge_still_preserves_render_only_for_a_still_render_row():
    rows = [{"domain": "y.com", "is_render_only": True,
             "status": "provider-test-candidate"}]
    build._merge_prior_verdicts(rows, {"y.com": {"status": "render-only"}})
    assert rows[0]["status"] == "render-only"


@pytest.mark.parametrize("status", ["live", "dead"])
def test_merge_preserves_liveness_verdicts_and_notes(status):
    rows = [{"domain": "z.com", "is_render_only": False,
             "status": "provider-test-candidate"}]
    build._merge_prior_verdicts(
        rows, {"z.com": {"status": status, "note": "demoted: non-retail"}}
    )
    assert rows[0]["status"] == status
    assert rows[0]["note"] == "demoted: non-retail"


def test_merge_preserves_dead_tombstones_the_generator_no_longer_emits():
    # Four demotions were followed by a generator SKIP and a fifth domain became
    # a registry literal, so a plain re-consolidation drops all five rows — and
    # with them the "Do not re-promote" rationale. A rebuild must not silently
    # delete a demotion record.
    rows = [{"domain": "kept.com", "tier": "bahrain", "priority_rank": 1,
             "is_render_only": False, "status": "live"}]
    merged = build._merge_prior_verdicts(rows, {
        "kept.com": {"status": "live"},
        "gone.com": {"domain": "gone.com", "tier": "bahrain", "priority_rank": 2,
                     "status": "dead", "note": "non-retail. Do not re-promote."},
    })
    by_domain = {r["domain"]: r for r in merged}
    assert by_domain["gone.com"]["note"].endswith("Do not re-promote.")
    assert [r["domain"] for r in merged] == ["kept.com", "gone.com"]  # re-sorted


def test_merge_does_not_resurrect_a_dropped_live_row():
    # Only DEAD tombstones survive: a live row the catalogs no longer carry is a
    # deliberate removal, and resurrecting it would re-admit a dropped source.
    rows = [{"domain": "kept.com", "tier": "bahrain", "priority_rank": 1,
             "is_render_only": False, "status": "live"}]
    merged = build._merge_prior_verdicts(rows, {
        "dropped.com": {"domain": "dropped.com", "tier": "bahrain",
                        "priority_rank": 2, "status": "live"},
    })
    assert [r["domain"] for r in merged] == ["kept.com"]


def test_rebuild_drops_no_row_and_touches_only_the_corrected_ones():
    # THE BLAST-RADIUS GATE the unit is judged on: regenerating against the
    # committed file as prior must reproduce it row-for-row.
    committed = json.loads(sr._CATALOG_DATA_PATH.read_text(encoding="utf-8"))
    prior = {r["domain"]: r for r in committed}
    rebuilt = build._merge_prior_verdicts(build.consolidate(), prior)
    assert [r["domain"] for r in rebuilt] == [r["domain"] for r in committed]
    assert rebuilt == committed, "a rebuild would change the committed registry data"


def test_measured_probe_record_is_carried_from_catalog_to_generated_row():
    row = {"domain": "q.bh", "integration_adapter": "fetch_page_price (mechanism=curl)",
           "mechanism": "curl_jsonld", "currency": "BHD", "country": "BH",
           "categories": ["fashion"], "sample_pdp_url": "https://q.bh/p/1",
           "priority_rank": 7, "measured": "2026-08-30 curl: 200, 1.000 BHD"}
    assert build._measured_note(row) == "2026-08-30 curl: 200, 1.000 BHD"
    assert build._measured_note({"domain": "q.bh"}) == ""


def test_liveness_gate_domain_filter_probes_only_the_named_rows():
    # `--domain` is what let this unit re-verdict the four corrected rows
    # without re-probing (and re-writing) all 368. Without it the correction's
    # diff is unreviewable.
    import asyncio

    from scripts import verify_bh_gcc_sources as verify

    probed = []

    async def _fake_probe(url, mechanism=""):
        probed.append(url)
        return "live", "http=200 +price"

    real_probe = verify._probe
    verify._probe = _fake_probe
    try:
        rows = [
            {"domain": "wanted.com", "tier": "gcc", "mechanism": "",
             "sample_url": "https://wanted.com/p/1", "is_render_only": False,
             "status": "provider-test-candidate"},
            {"domain": "www.other.com", "tier": "gcc", "mechanism": "",
             "sample_url": "https://other.com/p/1", "is_render_only": False,
             "status": "provider-test-candidate"},
        ]
        tally = asyncio.run(verify._run(rows, None, None, {"wanted.com"}))
    finally:
        verify._probe = real_probe
    assert probed == ["https://wanted.com/p/1"]
    assert tally["live"] == 1
    assert rows[0]["status"] == "live"
    assert rows[1]["status"] == "provider-test-candidate"  # untouched


def test_liveness_gate_domain_filter_is_www_insensitive():
    from scripts import verify_bh_gcc_sources as verify

    assert verify._norm_domain("WWW.Bfab.com ") == "bfab.com"
    assert verify._norm_domain(None) == ""


def test_no_other_generated_row_gained_a_probe_record():
    # Blast-radius pin: the rebuild must have touched ONLY the intended rows.
    rows = json.loads(sr._CATALOG_DATA_PATH.read_text(encoding="utf-8"))
    with_measured = {r["domain"] for r in rows if r.get("measured")}
    assert with_measured == set(CORRECTED)
